// Inclui acesso à operações básicas
#include <iostream>

/*
===================================
    Tradução:
    std = standard
    std::cout = character output
    << = insert
    '\n' = line break
===================================
*/

int main() {

    std::cout << "Olá mundo!" << '\n';
    std::cout << "Este é meu primeiro programa C++!";

    // Retornar 0 implica que não houve erros
    // Retornar 1 implica um erro
    return 0;
}
